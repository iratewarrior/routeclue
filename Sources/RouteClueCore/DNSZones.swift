import Foundation

public enum DNSZoneError: Error, CustomStringConvertible, Sendable, Equatable {
    case invalidZoneName(String)
    case emptyNameservers(String)
    case invalidNameserver(String)
    case symlinkTarget(String)
    case notOwned(String)
    case executionFailed(String)

    public var description: String {
        switch self {
        case let .invalidZoneName(name):
            return "Некорректное имя DNS зоны: '\(name)'. Имя должно состоять из латинских букв, цифр, дефисов и точек."
        case let .emptyNameservers(zone):
            return "Для включенной DNS зоны '\(zone)' не указано ни одного адреса nameserver."
        case let .invalidNameserver(ns):
            return "Некорректный адрес DNS-сервера: '\(ns)'. Ожидается валидный IPv4 или IPv6 адрес без пробелов и переносов строк."
        case let .symlinkTarget(target):
            return "Файл \(target) является символической ссылкой — операция отклонена для защиты системы."
        case let .notOwned(zone):
            return "Файл /etc/resolver/\(zone) не был создан RouteClue — операция отклонена для защиты сторонних сервисов."
        case let .executionFailed(msg):
            return "Ошибка применения DNS зон: \(msg)"
        }
    }
}

/// Split DNS для приватных зон через /etc/resolver, который поддерживается mDNSResponder.
/// Замечание: утилиты `dig` и `nslookup` игнорируют эти файлы — проверяйте через `dscacheutil` или браузер.
public enum DNSZones {
    public static let directory = "/etc/resolver"
    public static let fileHeader = "# Generated by RouteClue — do not edit"
    public static let legacyFileHeader = "# Generated by TunnelGuard — do not edit"

    /// Проверяет корректность доменного имени зоны и защищает от Path Traversal (../).
    public static func isValidZoneName(_ zone: String) -> Bool {
        guard !zone.isEmpty, zone.count <= 253 else { return false }
        if zone.contains("/") || zone.contains("\\") || zone.contains("..") { return false }
        let pattern = "^[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(\\.[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*$"
        return zone.range(of: pattern, options: .regularExpression) != nil
    }

    /// Проверяет валидность IPv4 или IPv6 адреса nameserver.
    /// Отклоняет пробелы, табуляции и переносы строк.
    public static func isValidNameserver(_ ns: String) -> Bool {
        if ns.contains(" ") || ns.contains("\t") || ns.contains("\n") || ns.contains("\r") {
            return false
        }
        let trimmed = ns.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        // IPv4 check
        if RouteManager.parseIPv4(trimmed) != nil {
            return true
        }

        // IPv6 check via inet_pton
        var sin6 = sockaddr_in6()
        return inet_pton(AF_INET6, trimmed, &sin6.sin6_addr) == 1
    }

    /// Проверяет, принадлежит ли существующий файл /etc/resolver/<zone> нашему приложению.
    public static func hasOwnership(zone: String) -> Bool {
        guard isValidZoneName(zone) else { return false }
        let path = "\(directory)/\(zone)"

        // Reject symlinks
        var isSymlink = false
        if let attrs = try? FileManager.default.attributesOfItem(atPath: path),
           let type = attrs[.type] as? FileAttributeType, type == .typeSymbolicLink {
            isSymlink = true
        }
        if isSymlink { return false }

        guard let text = contents(of: zone) else { return false }
        return text.contains(fileHeader) || text.contains(legacyFileHeader)
    }

    public static func installedZones() -> [String] {
        (try? FileManager.default.contentsOfDirectory(atPath: directory))?
            .filter { !$0.hasPrefix(".") && isValidZoneName($0) }
            .sorted() ?? []
    }

    public static func contents(of zone: String) -> String? {
        guard isValidZoneName(zone) else { return nil }
        return try? String(contentsOfFile: "\(directory)/\(zone)", encoding: .utf8)
    }

    public static func render(_ zone: DNSZone) -> String {
        var lines = [fileHeader]
        for ns in zone.nameservers {
            lines.append("nameserver \(ns)")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    public struct StagedEntry: Sendable, Equatable {
        public let zone: String
        public let stagedPath: String?
        public let enabled: Bool

        public init(zone: String, stagedPath: String?, enabled: Bool) {
            self.zone = zone
            self.stagedPath = stagedPath
            self.enabled = enabled
        }
    }

    /// Генерирует автономный bash-скрипт применения DNS зон с защитой от symlink, не-RouteClue файлов и TOCTOU.
    public static func makeApplyScript(
        stagedEntries: [StagedEntry],
        targetDirectory: String = directory,
        flushCache: Bool = true
    ) -> String {
        let qTargetDir = Shell.quote(targetDirectory)
        var lines: [String] = ["set -e", "mkdir -p \(qTargetDir)"]

        for entry in stagedEntries {
            let targetPath = "\(targetDirectory)/\(entry.zone)"
            let qTarget = Shell.quote(targetPath)

            if entry.enabled, let stagedPath = entry.stagedPath {
                let qStaged = Shell.quote(stagedPath)
                lines.append("""
                if [ -L \(qTarget) ]; then
                    echo "FAIL_SYMLINK: \(targetPath) is a symlink" >&2
                    exit 4
                fi
                if [ -e \(qTarget) ]; then
                    if ! grep -qE '^(# Generated by RouteClue|# Generated by TunnelGuard)' \(qTarget) 2>/dev/null; then
                        echo "FAIL_NOT_OWNED: \(targetPath) was not created by RouteClue" >&2
                        exit 5
                    fi
                fi
                cp \(qStaged) \(qTarget)
                chmod 644 \(qTarget)
                """)
            } else {
                lines.append("""
                if [ -L \(qTarget) ]; then
                    echo "FAIL_SYMLINK: \(targetPath) is a symlink" >&2
                    exit 4
                fi
                if [ -e \(qTarget) ]; then
                    if ! grep -qE '^(# Generated by RouteClue|# Generated by TunnelGuard)' \(qTarget) 2>/dev/null; then
                        echo "FAIL_NOT_OWNED: \(targetPath) was not created by RouteClue" >&2
                        exit 5
                    fi
                    rm -f \(qTarget)
                fi
                """)
            }
        }

        if flushCache {
            lines.append("/usr/bin/dscacheutil -flushcache")
            lines.append("/usr/bin/killall -HUP mDNSResponder 2>/dev/null || true")
        }

        return lines.joined(separator: "\n")
    }

    /// Генерирует автономный bash-скрипт удаления DNS зоны.
    public static func makeRemoveScript(
        zone: String,
        targetDirectory: String = directory,
        flushCache: Bool = true
    ) -> String {
        let targetPath = "\(targetDirectory)/\(zone)"
        let qTarget = Shell.quote(targetPath)

        var lines: [String] = [
            "set -e",
            """
            if [ -L \(qTarget) ]; then
                echo "FAIL_SYMLINK: \(targetPath) is a symlink" >&2
                exit 4
            fi
            if [ -e \(qTarget) ]; then
                if ! grep -qE '^(# Generated by RouteClue|# Generated by TunnelGuard)' \(qTarget) 2>/dev/null; then
                    echo "FAIL_NOT_OWNED: \(targetPath) was not created by RouteClue" >&2
                    exit 5
                fi
                rm -f \(qTarget)
            """
        ]

        if flushCache {
            lines.append("""
                /usr/bin/dscacheutil -flushcache
                /usr/bin/killall -HUP mDNSResponder 2>/dev/null || true
            """)
        }

        lines.append("""
                echo "REMOVED"
            else
                echo "NOT_INSTALLED"
            fi
            """)

        return lines.joined(separator: "\n")
    }

    /// Синхронизирует /etc/resolver с конфигурацией зон за один привилегированный вызов.
    @discardableResult
    public static func apply(_ zones: [DNSZone]) throws -> String {
        guard !zones.isEmpty else { return "No zones configured." }

        // Предварительная валидация
        for zone in zones {
            guard isValidZoneName(zone.zone) else {
                throw DNSZoneError.invalidZoneName(zone.zone)
            }
            if zone.enabled {
                guard !zone.nameservers.isEmpty else {
                    throw DNSZoneError.emptyNameservers(zone.zone)
                }
            }
            for ns in zone.nameservers {
                guard isValidNameserver(ns) else {
                    throw DNSZoneError.invalidNameserver(ns)
                }
            }
        }

        // Staging каталог с mode 0700 для защиты от стороннего чтения/подмены
        let staging = FileManager.default.temporaryDirectory
            .appendingPathComponent("rc-dns-\(ProcessInfo.processInfo.processIdentifier)-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: staging, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        _ = try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: staging.path)
        defer { try? FileManager.default.removeItem(at: staging) }

        var stagedEntries: [StagedEntry] = []
        var messages: [String] = []

        for zone in zones {
            if zone.enabled {
                let file = staging.appendingPathComponent(zone.zone)
                try render(zone).write(to: file, atomically: true, encoding: .utf8)
                _ = try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
                stagedEntries.append(StagedEntry(zone: zone.zone, stagedPath: file.path, enabled: true))
                messages.append("+ \(zone.zone) → \(zone.nameservers.joined(separator: ", "))")
            } else {
                stagedEntries.append(StagedEntry(zone: zone.zone, stagedPath: nil, enabled: false))
                messages.append("- \(zone.zone) removed")
            }
        }

        let script = makeApplyScript(stagedEntries: stagedEntries, targetDirectory: directory, flushCache: true)
        let result = try Shell.privileged(script)

        if !result.ok {
            if result.combined.contains("FAIL_SYMLINK") {
                throw DNSZoneError.symlinkTarget(result.combined)
            }
            if result.combined.contains("FAIL_NOT_OWNED") {
                throw DNSZoneError.notOwned(result.combined)
            }
            throw DNSZoneError.executionFailed(result.combined)
        }

        return (messages + ["DNS cache flushed."]).joined(separator: "\n")
    }

    @discardableResult
    public static func remove(zone: String) throws -> String {
        guard isValidZoneName(zone) else {
            throw DNSZoneError.invalidZoneName(zone)
        }

        let script = makeRemoveScript(zone: zone, targetDirectory: directory, flushCache: true)
        let result = try Shell.privileged(script)
        if !result.ok {
            if result.combined.contains("FAIL_SYMLINK") {
                throw DNSZoneError.symlinkTarget(result.combined)
            }
            if result.combined.contains("FAIL_NOT_OWNED") {
                throw DNSZoneError.notOwned(zone)
            }
            throw DNSZoneError.executionFailed(result.combined)
        }

        if result.stdout.contains("REMOVED") {
            return "Zone \(zone) removed."
        }
        return "Zone \(zone) was not installed."
    }

    public static func flush() throws {
        _ = try Shell.privileged("/usr/bin/dscacheutil -flushcache\n/usr/bin/killall -HUP mDNSResponder 2>/dev/null || true")
    }
}
